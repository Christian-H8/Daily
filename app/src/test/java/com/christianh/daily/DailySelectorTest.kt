package com.christianh.daily

import com.christianh.daily.domain.DailySelector
import com.christianh.daily.domain.EPOCH
import com.christianh.daily.domain.StableHash
import com.christianh.daily.domain.model.Entry
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test
import java.time.LocalDate

class DailySelectorTest {

    // Selection depends on the id and nothing else, so every other field is filler.
    private fun entry(id: String) = Entry(
        id = id,
        type = "principle",
        title = id,
        tagline = "",
        tags = emptyList(),
        related = emptyList(),
        words = 0,
        minutes = 1,
        sections = emptyList()
    )

    // Values generated by publish.py. Source of truth: corpus/tools/fixtures_hash.json
    private val ids = listOf(
        "epictetus-what-is-ours", "epictetus-not-things-but-opinions",
        "epictetus-wish-things-as-they-are", "epictetus-restored-not-lost",
        "epictetus-actor-in-a-play", "marcus-revoke-your-estimate",
        "marcus-take-away-the-opinion", "marcus-best-revenge",
        "marcus-obstacle-becomes-the-way", "shantideva-remedy-or-none",
        "boethius-fortune-turns", "seneca-more-things-frighten-us"
    )
    private val corpus = ids.map(::entry)

    @Test fun `hash matches the python implementation`() {
        assertEquals(391397487811367939L, StableHash.of("epictetus-what-is-ours"))
        assertEquals(-2132752984291615099L, StableHash.of("epictetus-not-things-but-opinions"))
        assertEquals(-2883207949946553796L, StableHash.of("epictetus-wish-things-as-they-are"))
    }

    @Test fun `order matches the python implementation`() {
        val expected = listOf(
            "marcus-best-revenge", "shantideva-remedy-or-none",
            "marcus-obstacle-becomes-the-way", "marcus-revoke-your-estimate",
            "epictetus-wish-things-as-they-are", "epictetus-not-things-but-opinions",
            "epictetus-what-is-ours", "marcus-take-away-the-opinion",
            "epictetus-actor-in-a-play", "boethius-fortune-turns",
            "epictetus-restored-not-lost", "seneca-more-things-frighten-us"
        )
        val actual = (0 until corpus.size).map {
            DailySelector.entryFor(EPOCH.plusDays(it.toLong()), corpus)!!.id
        }
        assertEquals(expected, actual)
    }

    @Test fun `same day always gives the same entry`() {
        val d = LocalDate.of(2026, 9, 12)
        assertEquals(
            DailySelector.entryFor(d, corpus)!!.id,
            DailySelector.entryFor(d, corpus)!!.id
        )
    }

    @Test fun `every window of n days is a full permutation`() {
        val n = corpus.size
        val seq = (0 until n * 5).map {
            DailySelector.entryFor(EPOCH.plusDays(it.toLong()), corpus)!!.id
        }
        for (start in 0..(seq.size - n)) {
            assertEquals(n, seq.subList(start, start + n).toSet().size)
        }
    }

    @Test fun `dates before the epoch do not crash`() {
        DailySelector.entryFor(EPOCH.minusDays(400), corpus)
    }

    @Test fun `empty corpus returns null`() {
        assertNull(DailySelector.entryFor(LocalDate.now(), emptyList()))
    }
}
